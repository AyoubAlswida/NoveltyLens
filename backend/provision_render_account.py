"""Provision the account after migrations on a Render instance without Shell."""

import os
import re

import psycopg

from config import settings


def main() -> None:
    email = os.environ.get("NOVELTY_LOGIN_EMAIL", "").strip().lower()
    password_hash = os.environ.get("NOVELTY_LOGIN_PASSWORD_HASH", "").strip()
    if not email or "@" not in email or email == "testnovelty@gmail.com":
        raise SystemExit("Set NOVELTY_LOGIN_EMAIL to your own email address.")
    if not re.fullmatch(r"pbkdf2_sha256\$260000\$[0-9a-f]{32}\$[0-9a-f]{64}", password_hash):
        raise SystemExit("Set NOVELTY_LOGIN_PASSWORD_HASH to a hash generated by auth.hash_password.")

    with psycopg.connect(settings.database_url) as conn:
        conn.execute(
            "INSERT INTO users (email, password_hash) VALUES (%s, %s) "
            "ON CONFLICT (email) DO UPDATE SET password_hash = EXCLUDED.password_hash",
            (email, password_hash),
        )


if __name__ == "__main__":
    main()
